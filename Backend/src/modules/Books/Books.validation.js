import Joi from 'joi'

export const createBooksSchema = Joi.object({
  title: Joi.string().required(),
  slug: Joi.string().required(),
  description: Joi.string().allow(null, ''),
  publisher_id: Joi.number().integer().allow(null, ''),
  format: Joi.string().allow(null, ''),
  isbn: Joi.string().allow(null, ''),
  barcode: Joi.string().allow(null, ''),
  warehouse_location: Joi.string().allow(null, ''),
  stock_qty: Joi.number().integer(),
  original_price: Joi.number().required(),
  sale_price: Joi.number().required(),
  sold_count: Joi.number().integer(),
  weight_grams: Joi.number().integer().required(),
  length_cm: Joi.number().integer().allow(null, ''),
  width_cm: Joi.number().integer().allow(null, ''),
  height_cm: Joi.number().integer().allow(null, ''),
  copyright_holder: Joi.string().allow(null, ''),
  license_end_date: Joi.date().allow(null, ''),
  avg_rating: Joi.number().allow(null, ''),
  review_count: Joi.number().integer().allow(null, ''),
  is_active: Joi.boolean().allow(null, ''),
  author_ids: Joi.array().items(Joi.number().integer()).allow(null, ''),
  category_ids: Joi.array().items(Joi.number().integer()).allow(null, ''),
  image_url: Joi.string().allow(null, ''),
})

